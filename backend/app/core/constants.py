"""Shared enums and protocol constants."""

from enum import StrEnum


class Role(StrEnum):
    FARMER = "farmer"
    VETERINARIAN = "veterinarian"
    PARAVET = "paravet"
    COOPERATIVE = "cooperative"
    ADMIN = "admin"


class Language(StrEnum):
    ENGLISH = "en"
    HINDI = "hi"
    MARATHI = "mr"


class CaseStatus(StrEnum):
    REPORTED = "reported"
    TRIAGED = "triaged"
    ASSIGNED = "assigned"
    IN_PROGRESS = "in_progress"
    RESOLVED = "resolved"
    CLOSED = "closed"


class Severity(StrEnum):
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"
    CRITICAL = "critical"


class AppointmentStatus(StrEnum):
    REQUESTED = "requested"
    SCHEDULED = "scheduled"
    COMPLETED = "completed"
    CANCELLED = "cancelled"


class NotificationStatus(StrEnum):
    PENDING = "pending"
    SENT = "sent"
    READ = "read"
    FAILED = "failed"


