"""Advisory agents: vaccination, nutrition, environment, market intelligence and finance."""

from datetime import UTC, date, datetime, timedelta

from sqlalchemy import select

from app.agents.state import GuardianState
from app.models import (
    Animal,
    EnvironmentalRecord,
    FeedRecord,
    LivestockMarketPrice,
    NutritionProfile,
    WaterRecord,
)
from app.services.access import animal_query, primary_farm
from app.services.finance import financial_summary
from app.services.vaccination import create_vaccination_reminders, ensure_animal_schedule, schedule_items
from app.services.weather import assess_environment, get_weather


def _event(agent: str, detail: str, status: str = "ok") -> dict:
    return {"agent": agent, "status": status, "detail": detail, "at": datetime.now(UTC).isoformat()}


def _pop(plan: list[str], name: str) -> list[str]:
    return plan[1:] if plan and plan[0] == name else plan


def vaccination_node(state: GuardianState) -> dict:
    db = state["db"]
    user = state["user"]
    plan = _pop(list(state.get("plan") or []), "vaccination")
    animal = state.get("animal")
    data = dict(state.get("data") or {})

    if animal:
        animal_ids = [animal.id]
    else:
        animal_ids = [row.id for row in db.scalars(animal_query(db, user)).all()][:50]

    animals = db.scalars(select(Animal).where(Animal.id.in_(animal_ids))).all() if animal_ids else []
    for row in animals:
        ensure_animal_schedule(db, row)
    db.flush()
    items = schedule_items(db, animal_ids, within_days=30)
    reminders = create_vaccination_reminders(db, animal_ids) if animal_ids else 0
    data["schedule"] = [
        {
            "animal_name": item["animal_name"],
            "vaccine_name": item["vaccine_name"],
            "status": item["status"],
            "due_on": item["due_on"].isoformat(),
            "source_reference": item["source_reference"],
        }
        for item in items[:12]
    ]
    data["reminders_created"] = reminders
    data["source"] = "Vaccine catalogue with recorded protocol references; no schedule is generated by the LLM."

    return {
        "data": data,
        "plan": plan,
        "trace": [_event("vaccination", f"due_or_overdue={len(items)}, reminders_created={reminders}")],
        "agents_used": ["vaccination"],
    }


def nutrition_node(state: GuardianState) -> dict:
    db = state["db"]
    user = state["user"]
    plan = _pop(list(state.get("plan") or []), "nutrition")
    animal = state.get("animal")
    data = dict(state.get("data") or {})
    since = datetime.now(UTC) - timedelta(days=14)

    if animal:
        animals = [animal]
    else:
        animals = db.scalars(animal_query(db, user)).all()[:20]
    animal_ids = [row.id for row in animals]

    feeds = (
        db.scalars(
            select(FeedRecord)
            .where(FeedRecord.animal_id.in_(animal_ids), FeedRecord.recorded_at >= since)
            .order_by(FeedRecord.recorded_at.desc())
        ).all()
        if animal_ids
        else []
    )
    waters = (
        db.scalars(
            select(WaterRecord)
            .where(WaterRecord.animal_id.in_(animal_ids), WaterRecord.recorded_at >= since)
            .order_by(WaterRecord.recorded_at.desc())
        ).all()
        if animal_ids
        else []
    )

    species_id = animals[0].species_id if animals else None
    profile = None
    if species_id:
        profile = db.scalar(
            select(NutritionProfile).where(NutritionProfile.species_id == species_id, NutritionProfile.stage == "maintenance")
        ) or db.scalar(select(NutritionProfile).where(NutritionProfile.species_id == species_id))

    gaps = []
    if not feeds:
        gaps.append("no feed records in the last 14 days")
    if not waters:
        gaps.append("no water observation recorded")
    if animals and any(not row.weight_kg for row in animals):
        gaps.append("body weight missing for one or more animals")

    data["profile"] = (
        {
            "feed_guidance": profile.feed_guidance,
            "water_litres": profile.water_litres,
            "minerals": profile.minerals,
            "reference_source": profile.reference_source,
        }
        if profile
        else None
    )
    data["records"] = [
        {
            "feed_type": row.feed_type,
            "quantity_kg": row.quantity_kg,
            "recorded_at": row.recorded_at.isoformat(),
            "mineral_supplement": row.mineral_supplement,
        }
        for row in feeds[:10]
    ]
    data["water_records"] = len(waters)
    data["gap"] = "; ".join(gaps) if gaps else None
    data["referral"] = "Specific dietary or medical decisions must be referred to a veterinarian or qualified animal nutrition professional."

    return {
        "data": data,
        "plan": plan,
        "trace": [_event("nutrition", f"feed_records={len(feeds)}, water_records={len(waters)}, gaps={len(gaps)}")],
        "agents_used": ["nutrition"],
    }


def environment_node(state: GuardianState) -> dict:
    db = state["db"]
    user = state["user"]
    plan = _pop(list(state.get("plan") or []), "environment")
    data = dict(state.get("data") or {})
    farm = state.get("farm") or primary_farm(db, user)

    weather = get_weather(farm)
    weather_serializable = dict(weather)
    weather_serializable["forecast"] = [
        {**day, "date": day["date"].isoformat() if isinstance(day.get("date"), date) else day.get("date")}
        for day in weather.get("forecast", [])
    ]
    latest = None
    if farm:
        latest = db.scalar(
            select(EnvironmentalRecord)
            .where(EnvironmentalRecord.farm_id == farm.id)
            .order_by(EnvironmentalRecord.recorded_at.desc())
        )
    flags = assess_environment(latest)
    data["weather"] = weather_serializable
    data["latest_observation"] = (
        {
            "recorded_at": latest.recorded_at.isoformat(),
            "temperature_c": latest.temperature_c,
            "humidity_pct": latest.humidity_pct,
            "shed_cleanliness": latest.shed_cleanliness,
            "water_available": latest.water_available,
        }
        if latest
        else None
    )
    data["flags"] = flags
    data["note"] = "Environmental observations do not confirm disease."

    return {
        "data": data,
        "plan": plan,
        "trace": [_event("environment", f"weather_live={bool(weather.get('available'))}, flags={len(flags)}")],
        "agents_used": ["environment"],
    }


def market_node(state: GuardianState) -> dict:
    db = state["db"]
    user = state["user"]
    plan = _pop(list(state.get("plan") or []), "market")
    farm = state.get("farm") or primary_farm(db, user)
    district = (farm.district if farm else None) or getattr(user, "district", None) or "Pune"
    data = dict(state.get("data") or {})
    since = date.today() - timedelta(days=90)

    rows = db.scalars(
        select(LivestockMarketPrice)
        .where(
            LivestockMarketPrice.district.ilike(district),
            LivestockMarketPrice.observed_on >= since,
            LivestockMarketPrice.observed_on <= date.today(),
        )
        .order_by(LivestockMarketPrice.observed_on.desc())
    ).all()

    seen: set[tuple[str, str]] = set()
    latest: list[dict] = []
    for row in rows:
        key = (row.category, row.unit)
        if key in seen:
            continue
        seen.add(key)
        latest.append(
            {
                "category": row.category,
                "price_per_unit": row.price_per_unit,
                "unit": row.unit,
                "market_name": row.market_name,
                "district": row.district,
                "observed_on": row.observed_on.isoformat(),
                "source": row.source,
                "source_url": row.source_url,
                "is_demo": row.is_demo,
            }
        )

    data["district"] = district
    data["prices"] = latest[:12]
    data["sources"] = sorted({row.source for row in rows})
    data["demo_data"] = any(row.is_demo for row in rows)

    return {
        "data": data,
        "plan": plan,
        "trace": [_event("market", f"district={district}, price_rows={len(latest)}, demo={data['demo_data']}")],
        "agents_used": ["market"],
    }


def finance_node(state: GuardianState) -> dict:
    db = state["db"]
    user = state["user"]
    plan = _pop(list(state.get("plan") or []), "finance")
    data = dict(state.get("data") or {})
    summary = financial_summary(db, user, period_days=30)
    data["summary"] = summary
    return {
        "data": data,
        "plan": plan,
        "trace": [_event("finance", f"net={summary['net']}, estimated_loss={summary['estimated_loss']}")],
        "agents_used": ["finance"],
    }
