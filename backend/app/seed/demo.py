def _ensure_reference_data(db: Session) -> dict[str, Species]:
    species_map: dict[str, Species] = {}
    for code, name_en, name_hi, name_mr, icon, milk, egg, weight, water, temp, gestation, production in SPECIES_SEED:
        existing = db.scalar(select(Species).where(Species.code == code))
        if not existing:
            existing = Species(
                code=code,
                name_en=name_en,
                name_hi=name_hi,
                name_mr=name_mr,
                icon=icon,
                milk_bearing=milk,
                egg_bearing=egg,
                profile={
                    "adult_weight_kg": weight,
                    "water_litres_per_day": water,
                    "normal_temp_c": temp,
                    "gestation_days": gestation,
                    "production": production,
                },
            )
            db.add(existing)
            db.flush()
        species_map[code] = existing

    for code, rows in BREED_SEED.items():
        species = species_map[code]
        existing_names = {name for name in db.scalars(select(Breed.name).where(Breed.species_id == species.id)).all()}
        for name, purpose, origin in rows:
            if name not in existing_names:
                db.add(Breed(species_id=species.id, name=name, purpose=purpose, origin=origin))

    for row in VACCINE_PROTOCOLS:
        species = species_map.get(row["species"])
        if not species:
            continue
        exists = db.scalar(
            select(VaccineCatalog).where(
                VaccineCatalog.species_id == species.id, VaccineCatalog.name == row["name"]
            )
        )
        if not exists:
            db.add(
                VaccineCatalog(
                    species_id=species.id,
                    name=row["name"],
                    disease=row["disease"],
                    age_weeks=row["age_weeks"],
                    booster_days=row["booster_days"],
                    source_reference=row["source_reference"],
                    is_verified=True,
                )
            )

    for code, (dm, guidance, water, minerals, source) in NUTRITION_SEED.items():
        species = species_map[code]
        exists = db.scalar(select(NutritionProfile).where(NutritionProfile.species_id == species.id))
        if not exists:
            db.add(
                NutritionProfile(
                    species_id=species.id,
                    stage="maintenance",
                    dry_matter_kg=dm,
                    feed_guidance=guidance,
                    water_litres=water,
                    minerals=minerals,
                    reference_source=source,
                )
            )

    if not db.scalar(select(KnowledgeDocument.id).limit(1)):
        docs = [
            ("Recognising urgent livestock warning signs", "health", None,
             "Difficulty breathing, inability to stand, convulsions, bloat, severe bleeding, persistent high fever, refusal to drink, or sudden death require immediate veterinary contact. This guidance does not diagnose a disease and does not replace a veterinarian.",
             "State animal husbandry department emergency advisory"),
            ("Foot and mouth disease: prevention basics", "disease", "cattle",
             "Foot and mouth disease is a contagious viral disease of cloven-hoofed animals. Prevention relies on vaccination as per the local veterinary schedule, restricted movement of animals, and immediate reporting of blisters or excessive salivation to a veterinarian.",
             "DAHD foot and mouth disease control programme"),
            ("PPR in goats and sheep", "disease", "goat",
             "Peste des petits ruminants affects goats and sheep. Signs may include fever, nasal discharge, diarrhoea and mouth lesions. Vaccination per a veterinarian-approved schedule and avoiding contact with unknown animals are core preventive measures.",
             "ICAR-CIRG PPR control advisory"),
            ("Heat stress management in dairy animals", "welfare", "cattle",
             "Provide shade, ventilation and unlimited clean drinking water during hot weather. Offer feed during cooler hours and avoid moving animals in peak heat. Persistent panting or collapse needs veterinary attention.",
             "ICAR heat stress advisory for dairy animals"),
            ("Clean milk production and mastitis awareness", "production", "buffalo",
             "Wash hands and udder before milking, use clean utensils, and discard milk from an animal receiving veterinary treatment as directed. A hot, swollen quarter or changed milk requires veterinary examination; milk withdrawal periods must be followed.",
             "National dairy development clean milk guidance"),
            ("Poultry biosecurity and Newcastle disease", "disease", "chicken",
             "Keep visitors and wild birds away from the flock, clean feeders and drinkers, and follow the local vaccination schedule for Newcastle disease. Sudden mortality or nervous signs must be reported to a veterinary professional.",
             "State veterinary department poultry advisory"),
        ]
        for title, category, species_code, content, source in docs:
            db.add(
                KnowledgeDocument(
                    title=title,
                    category=category,
                    species_code=species_code,
                    content=content,
                    source=source,
                    is_verified=True,
                )
            )

    db.flush()
